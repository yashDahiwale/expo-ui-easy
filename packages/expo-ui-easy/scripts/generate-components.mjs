// Generates src/android/components/generated.ts and test/generated-contract.test-d.ts from manifest/components.json.
//   node scripts/generate-components.mjs           write the files
//   node scripts/generate-components.mjs --check   fail if the files are out of date (used by the tests and CI)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(readFileSync(join(root, 'manifest/components.json'), 'utf8'));
const check = process.argv.includes('--check');

const PRESETS = {
  stretch: { host: 'STRETCH', fill: false },
  stretchFill: { host: 'STRETCH', fill: true },
  fillParent: { host: 'FILL_PARENT', fill: false },
  rangePicker: { host: 'RANGE_PICKER', fill: true },
};
const CATEGORY_ORDER = ['selection', 'sliders', 'text', 'buttons', 'progress', 'pickers', 'layout', 'media', 'scrollables', 'overlays', 'bars'];

const wrapped = manifest.components.filter((c) => c.kind === 'wrapped');
const families = manifest.components.filter((c) => c.kind === 'variants');
const generated = [...wrapped, ...families];
for (const c of families) {
  const v = c.variants;
  if (v === undefined || !(v.default in v.map)) throw new Error(`${c.name}: "variants" needs a map that contains its default`);
}
for (const c of generated) {
  if (c.hostPreset !== undefined && !(c.hostPreset in PRESETS)) throw new Error(`${c.name}: unknown hostPreset "${c.hostPreset}"`);
  if (!CATEGORY_ORDER.includes(c.category)) throw new Error(`${c.name}: unknown category "${c.category}"`);
}

// ------------------------------------------------------------------------------------------------
const header = (what) => `// AUTO-GENERATED by scripts/generate-components.mjs from manifest/components.json. DO NOT EDIT.\n// ${what}\n`;

function variantsCall(c) {
  const { prop, default: def, map, staticsFrom } = c.variants;
  const opts = [`displayName: '${c.name}'`];
  if (c.rename) opts.push(`rename: { ${Object.entries(c.rename).map(([k, v]) => `${k}: '${v}'`).join(', ')} }`);
  const entries = Object.entries(map).map(([variant, native]) => `    ${variant}: wrap(Expo.${native}, { ${opts.join(', ')} }),`);
  return `export const ${c.name} = createVariants({
  displayName: '${c.name}',
  prop: '${prop}',
  defaultVariant: '${def}',
  variants: {
${entries.join('\n')}
  },${staticsFrom ? `\n  staticsFrom: Expo.${staticsFrom},` : ''}
});
export type ${c.name}Props = ComponentProps<typeof ${c.name}>;`;
}

function wrapCall(c) {
  const opts = [`displayName: '${c.name}'`];
  if (c.rename) opts.push(`rename: { ${Object.entries(c.rename).map(([k, v]) => `${k}: '${v}'`).join(', ')} }`);
  if (c.hostStyleProp) opts.push(`hostStyleProp: '${c.hostStyleProp}'`);
  if (c.hostPreset) {
    const p = PRESETS[c.hostPreset];
    opts.push(`hostDefaults: ${p.host}`);
    if (p.fill) opts.push('leadingModifiers: FILL_WIDTH');
  }
  const type = c.explicitType ? `: NativeComponent<typeof Expo.${c.name}>` : '';
  return `export const ${c.name}${type} = wrap(Expo.${c.name}, { ${opts.join(', ')} });\nexport type ${c.name}Props = ComponentProps<typeof ${c.name}>;`;
}

let components = header('Wrapped Expo UI components. Edit the manifest, not this file.');
components += `
import * as Expo from '@expo/ui/jetpack-compose';
import { fillMaxWidth, type ModifierConfig } from '@expo/ui/jetpack-compose/modifiers';
import type { ComponentProps } from 'react';
import { createVariants } from '../internal/variants';
import { wrap, type NativeComponent } from '../internal/wrap';

const FILL_WIDTH: readonly ModifierConfig[] = [fillMaxWidth()];
// Presets are documented in manifest/components.json ("presets").
const STRETCH = { hostProps: { matchContents: { vertical: true } }, style: { alignSelf: 'stretch' } } as const;
const FILL_PARENT = { hostProps: { matchContents: false }, style: { flex: 1 } } as const;
const RANGE_PICKER = { hostProps: { matchContents: false }, style: { alignSelf: 'stretch', height: 480 } } as const;
`;
for (const cat of CATEGORY_ORDER) {
  const group = generated.filter((c) => c.category === cat);
  if (group.length === 0) continue;
  components += `\n// --- ${cat} ${'-'.repeat(Math.max(3, 70 - cat.length))}\n`;
  components += group.map((c) => (c.kind === 'variants' ? variantsCall(c) : wrapCall(c))).join('\n') + '\n';
}

// ------------------------------------------------------------------------------------------------
let contract = header('Compile-time checks that the manifest matches Expo\'s real prop types.');
contract += `
import type { ComponentProps, JSXElementConstructor } from 'react';
import type * as Expo from '@expo/ui/jetpack-compose';

type Has<C extends JSXElementConstructor<any>, K extends string> = K extends keyof ComponentProps<C> ? true : false;
declare function assertTrue<T extends true>(): void;
declare function assertFalse<T extends false>(): void;

export function contract(): void {
`;
for (const c of generated) {
  // A variant family checks every native component it can render.
  const natives = c.kind === 'variants' ? Object.values(c.variants.map) : [c.name];
  for (const native of natives) {
    contract += `  // ${c.name}${native === c.name ? '' : ` (${native})`}\n`;
    for (const [rn, expo] of Object.entries(c.rename ?? {})) {
      contract += `  assertTrue<Has<typeof Expo.${native}, '${expo}'>>(); // rename target exists in Expo\n`;
      contract += `  assertFalse<Has<typeof Expo.${native}, '${rn}'>>(); // RN name does not shadow an Expo prop\n`;
    }
    contract += c.hostStyleProp === 'containerStyle'
      ? `  assertTrue<Has<typeof Expo.${native}, 'style'>>(); // Expo has its own style, so the Host style is containerStyle\n`
      : `  assertFalse<Has<typeof Expo.${native}, 'style'>>(); // no Expo style: the Host style is style\n`;
  }
}
contract += '}\n';

// ------------------------------------------------------------------------------------------------
const outputs = [
  ['src/android/components/generated.ts', components],
  ['test/generated-contract.test-d.ts', contract],
];
let stale = false;
for (const [rel, content] of outputs) {
  const path = join(root, rel);
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      console.error(`OUT OF DATE: ${rel} (run \`npm run generate\`)`);
      stale = true;
    }
  } else {
    writeFileSync(path, content);
    console.log(`wrote ${rel}`);
  }
}
if (stale) process.exit(1);
